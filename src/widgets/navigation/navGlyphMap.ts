/** One distinct icon per page, so no two sidebar items look the same. */
export function getNavigationGlyphName(pathname: string): GlyphName {
  if (pathname.startsWith('/telephony')) return 'phone'
  if (pathname.startsWith('/settings')) return 'management'
  if (pathname.startsWith('/salary')) return 'salary'
  if (pathname.startsWith('/member/attendance') || pathname.startsWith('/ceo/attendance')) return 'attendance'
  if (pathname.startsWith('/member')) return 'member'
  if (pathname.startsWith('/ceo/ai')) return 'ai'
  if (pathname.startsWith('/ceo/users')) return 'users'
  if (pathname.startsWith('/ceo/team-updates')) return 'team-updates'
  if (pathname.startsWith('/ceo/website-stats')) return 'website'
  if (pathname.startsWith('/ceo/workday-overrides')) return 'workday'
  if (pathname.startsWith('/ceo/management')) return 'management'
  if (pathname.startsWith('/ceo')) return 'ceo'
  if (pathname.startsWith('/cims-team')) return 'team'
  if (pathname.startsWith('/crm/my-leads')) return 'my-leads'
  if (pathname.startsWith('/crm/customers') || pathname.startsWith('/outbound-crm/customers')) return 'customers'
  if (pathname.startsWith('/crm/archived') || pathname.startsWith('/outbound-crm/archived')) return 'archive'
  if (pathname.startsWith('/outbound-crm/statuses')) return 'statuses'
  if (pathname.startsWith('/crm') || pathname.startsWith('/outbound-crm')) return 'crm'
  if (pathname.startsWith('/faults')) return 'salary'
  if (pathname.startsWith('/payment')) return 'payment'
  if (pathname.startsWith('/wordpress')) return 'wordpress'
  if (pathname.startsWith('/updates')) return 'updates'
  if (pathname.startsWith('/cognilabsai/chat')) return 'cognilabsai-chat'
  if (pathname.startsWith('/cognilabsai/kanban')) return 'ai-kanban'
  if (pathname.startsWith('/cognilabsai/media-contexts')) return 'media'
  if (pathname.startsWith('/cognilabsai/integrations')) return 'cognilabsai-integrations'
  if (pathname.startsWith('/cognilabsai/comment-automation')) return 'instagram'
  if (pathname.startsWith('/audit')) return 'audit'
  if (pathname.startsWith('/developer-kpi')) return 'kpi'
  if (pathname.startsWith('/integrations')) return 'integrations'
  if (pathname.startsWith('/auth')) return 'auth'
  if (pathname.startsWith('/projects') || pathname.startsWith('/boards')) return 'projects'
  return 'default'
}
